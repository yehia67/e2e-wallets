#!/usr/bin/env node
// Generates claude-skill/wallets-e2e/ from packages/knowledge, the single source of truth.
// The Claude skill format wants SKILL.md plus references/ as real files, so they are copied here
// rather than symlinked; edit packages/knowledge and re-run this script.
import { execFileSync } from 'node:child_process';
import { cpSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = dirname(dirname(fileURLToPath(import.meta.url)));
const src = join(repo, 'packages/knowledge');
const out = join(repo, 'claude-skill/wallets-e2e');
const zipPath = join(repo, 'claude-skill/wallets-e2e-skill-upload.zip');

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, 'references'), { recursive: true });
cpSync(join(src, 'SKILL.md'), join(out, 'SKILL.md'));
cpSync(join(src, 'references'), join(out, 'references'), { recursive: true });
writeFileSync(
  join(out, '.generated'),
  'Generated by scripts/build-claude-skill.mjs from packages/knowledge. Do not edit here.\n',
);

// Rebuilt from scratch each time: `zip` adds to an existing archive rather than replacing it, so a
// renamed or deleted guide would otherwise linger in the upload forever.
rmSync(zipPath, { force: true });
try {
  // SKILL.md must sit at the archive root — the uploader looks for it there, not inside a folder.
  // `.DS_Store` is excluded explicitly: Finder writes them inside references/ and they survive -r.
  execFileSync('zip', ['-q', '-r', zipPath, 'SKILL.md', 'references', '-x', '*.DS_Store'], {
    cwd: out,
  });
} catch (error) {
  const reason = /** @type {NodeJS.ErrnoException} */ (error).code === 'ENOENT'
    ? '`zip` is not installed or not on PATH.'
    : String(error);
  console.error(`Skill folder written, but the upload zip could not be created: ${reason}`);
  console.error(`Create it manually: cd ${out} && zip -r ${zipPath} SKILL.md references`);
  process.exit(1);
}

console.log(`Claude skill written to ${out}`);
console.log(`Upload zip written to ${zipPath}`);
